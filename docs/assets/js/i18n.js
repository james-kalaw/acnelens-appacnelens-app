export const LANGS = { en: "English", fil: "Filipino" };
const KEY = "acnelens.lang";

function detect() {
  try { const s = localStorage.getItem(KEY); if (s && STR[s]) return s; } catch {}
  const prefs = navigator.languages || [navigator.language || "en"];
  return prefs.some((l) => /^(fil|tl)\b/i.test(l)) ? "fil" : "en";
}
let lang = detect();
document.documentElement.lang = lang === "fil" ? "fil" : "en";

export const getLang = () => lang;
export function setLang(l) {
  if (!STR[l]) return;
  lang = l;
  try { localStorage.setItem(KEY, l); } catch {}
  document.documentElement.lang = l === "fil" ? "fil" : "en";
}
/** Locale for dates: device default in English, Filipino formatting in Filipino. */
export const dateLocale = () => (lang === "fil" ? "fil-PH" : undefined);

/** Translate a key; {name} placeholders are filled from vars. Falls back to English. */
export function t(key, vars = {}) {
  let s = STR[lang][key];
  if (s == null) s = STR.en[key];
  if (s == null) { console.warn("i18n: missing key", key); return key; }
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
}
/** Filipino explanation for an ingredient; English uses the text from rules.js. */
export const ingText = (item) => (lang === "fil" ? STR.fil["ing." + item.id] ?? item.mechanism : item.mechanism);

/** Fill every [data-i18n] element (innerHTML) and [data-i18n-aria] label in root. */
export function applyStatic(root = document) {
  for (const el of root.querySelectorAll("[data-i18n]")) el.innerHTML = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-aria]")) el.setAttribute("aria-label", t(el.dataset.i18nAria));
  for (const el of root.querySelectorAll("[data-i18n-alt]")) el.setAttribute("alt", t(el.dataset.i18nAlt));
}
